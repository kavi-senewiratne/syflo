'use strict';
// Concatenates anchor.js + bridge-core.js into bridge.js, the single classic
// script the backend serves at /__syflo/bridge.js. Run: node bridge/build-bridge.js
const fs = require('fs');
const path = require('path');

const DIR = __dirname;
const OUT = path.join(DIR, 'bridge.js');

function build() {
  const anchor = fs.readFileSync(path.join(DIR, 'anchor.js'), 'utf8');
  const core = fs.readFileSync(path.join(DIR, 'bridge-core.js'), 'utf8');
  // The wrapper's own `module`/`exports` shadow any globals of the host page,
  // so anchor.js always takes its window.SyfloAnchor branch in the browser.
  return (
    '/* GENERATED by bridge/build-bridge.js from anchor.js + bridge-core.js - do not edit. */\n' +
    '(function () {\n' +
    'var module, exports;\n' +
    anchor + '\n' +
    core + '\n' +
    '})();\n'
  );
}

module.exports = { build, OUT };

if (require.main === module) {
  fs.writeFileSync(OUT, build());
  console.log('wrote ' + OUT);
}
